def try_fetch_live_world_bank_data() -> dict:
    """
    Attempt to fetch World Bank financial inclusion data.
    Returns dict mapping country_code -> financial_access_pct or empty dict on failure.
    Indicator: FX.OWN.TOTL.ZS (Account ownership at financial institution)
    """
    try:
        url = "https://api.worldbank.org/v2/country/all/indicator/FX.OWN.TOTL.ZS?format=json&date=2021:2023&per_page=300&mrv=1"
        with httpx.Client(timeout=8.0) as client:
            resp = client.get(url)
            if resp.status_code == 200:
                data = resp.json()
                result = {}
                if len(data) > 1 and data[1]:
                    for item in data[1]:
                        code = item.get("countryiso3code", "")
                        val = item.get("value")
                        if code and val is not None:
                            result[code] = round(float(val), 1)
                logger.info(f"World Bank: fetched {len(result)} countries")
                return result
    except Exception as e:
        logger.warning(f"World Bank fetch failed: {e}")
    return {}


