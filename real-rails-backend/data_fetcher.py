@lru_cache(maxsize=1)
def fetch_all_schemes() -> list:
    """
    Returns enriched scheme data. Attempts to layer live World Bank data
    on top of the authoritative curated dataset.
    Data source is tagged per record.
    """
    wb_data = try_fetch_live_world_bank_data()

    enriched = []
    for scheme in AUTHORITATIVE_RTP_DATA:
        s = dict(scheme)
        # Try to enrich with World Bank financial inclusion data
        iso3_candidates = [k for k, v in ISO3_TO_ISO2.items() if v == s.get("country_code")]
        for iso3 in iso3_candidates:
            if iso3 in wb_data:
                s["financial_inclusion_pct"] = wb_data[iso3]
                s["data_source"] = s.get("data_source", "") + " + World Bank WDI"
                break
        enriched.append(s)

    return enriched
